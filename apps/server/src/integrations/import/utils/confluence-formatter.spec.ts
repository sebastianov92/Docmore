import { load } from 'cheerio';
import {
  breadcrumbParent,
  calloutTypeFor,
  confluenceBodyHtml,
  confluenceTitle,
  languageFromBrush,
  lozengeColor,
  normalizeAttachmentHref,
  pageAttachments,
  parseIndexTree,
  stripSpacePrefix,
  titleFromFileName,
} from './confluence-formatter';

const page = (body: string, head = '') => `<!doctype html><html><head>${head}</head><body class="theme-default">
<div id="page"><div id="main"><div id="main-header">
<div id="breadcrumb-section"><ol id="breadcrumbs"><li class="first"><span><a href="index.html">DOCS</a></span></li><li><span><a href="Parent-Page_100.html">Parent Page</a></span></li></ol></div>
<h1 id="title-heading" class="pagetitle"><span id="title-text">DOCS : Child page</span></h1></div>
<div id="content" class="page view"><div class="page-metadata">Created by <span class='author'>Ana</span></div>
<div id="main-content" class="wiki-content group">${body}</div>
<div class="pageSection group"><div class="pageSectionHeader"><h2 id="attachments" class="pageSectionTitle">Attachments:</h2></div>
<div class="greybox" align="left"><img src="images/icons/bullet_blue.gif" height="8" width="8" alt=""/> <a href="attachments/200/300.png">diagram.png</a> (image/png)<br/>
<img src="images/icons/bullet_blue.gif" height="8" width="8" alt=""/> <a href="attachments/200/301.drawio">diagram</a> (application/vnd.jgraph.mxfile)<br/></div></div>
</div></div><div id="footer"><p>Document generated by Confluence</p></div></div></body></html>`;

describe('confluence-formatter', () => {
  it('reads titles with and without the space prefix', () => {
    expect(stripSpacePrefix('DOCS : Child page')).toBe('Child page');
    expect(stripSpacePrefix('Plain title')).toBe('Plain title');
    expect(confluenceTitle(load(page('<p>x</p>')), 'fallback')).toBe('Child page');
    expect(confluenceTitle(load('<html><head><title>DOCS : From head</title></head></html>'), 'f')).toBe('From head');
    expect(confluenceTitle(load('<html></html>'), 'fallback')).toBe('fallback');
    expect(titleFromFileName('Release-Notes_4521.html')).toBe('Release Notes');
  });

  it('finds the parent from the breadcrumbs', () => {
    expect(breadcrumbParent(load(page('')))).toBe('Parent-Page_100.html');
    expect(breadcrumbParent(load('<ol id="breadcrumbs"><li><a href="index.html">DOCS</a></li></ol>'))).toBeNull();
  });

  it('parses the page tree out of index.html in document order', () => {
    const index = `<div id="main-content"><h2>Available Pages:</h2><ul>
      <li><a href="Home_1.html">Home</a><ul>
        <li><a href="Guide_2.html">Guide</a><ul><li><a href="Install_3.html">Install</a></li></ul></li>
        <li><a href="FAQ_4.html">FAQ</a></li>
      </ul></li>
      <li><a href="Other_5.html">Other</a></li>
    </ul></div>`;
    const tree = parseIndexTree(index);
    expect(tree.get('Home_1.html')).toEqual({ parentFile: null, order: 0 });
    expect(tree.get('Guide_2.html')).toEqual({ parentFile: 'Home_1.html', order: 1 });
    expect(tree.get('Install_3.html')).toEqual({ parentFile: 'Guide_2.html', order: 2 });
    expect(tree.get('FAQ_4.html')).toEqual({ parentFile: 'Home_1.html', order: 3 });
    expect(tree.get('Other_5.html')).toEqual({ parentFile: null, order: 4 });
  });

  it('lists the attachments section with mime types', () => {
    expect(pageAttachments(load(page('')))).toEqual([
      { href: 'attachments/200/300.png', fileName: 'diagram.png', mimeType: 'image/png' },
      { href: 'attachments/200/301.drawio', fileName: 'diagram', mimeType: 'application/vnd.jgraph.mxfile' },
    ]);
  });

  it('maps thumbnails and download links onto the archived files', () => {
    expect(normalizeAttachmentHref('download/thumbnails/200/300.png?version=1&api=v2')).toBe('attachments/200/300.png');
    expect(normalizeAttachmentHref('/download/attachments/200/doc.pdf')).toBe('attachments/200/doc.pdf');
    expect(normalizeAttachmentHref('attachments/200/300.png#x')).toBe('attachments/200/300.png');
  });

  it('maps brushes, lozenges and macro classes', () => {
    expect(languageFromBrush('brush: java; gutter: false; theme: Confluence')).toBe('java');
    expect(languageFromBrush('brush: py; theme: Confluence')).toBe('python');
    expect(languageFromBrush('brush: text')).toBe('');
    expect(languageFromBrush(undefined)).toBe('');
    expect(lozengeColor('status-macro aui-lozenge aui-lozenge-success')).toBe('green');
    expect(lozengeColor('status-macro aui-lozenge')).toBe('gray');
    expect(calloutTypeFor('confluence-information-macro confluence-information-macro-warning')).toBe('danger');
    expect(calloutTypeFor('confluence-information-macro confluence-information-macro-tip')).toBe('success');
    expect(calloutTypeFor('aui-message aui-message-warning')).toBe('warning');
  });

  it('keeps only the page body and converts the macros', () => {
    const html = confluenceBodyHtml(
      page(`
        <p>Intro <span class="confluence-link"><a href="Other_5.html">Other</a></span> <a class="confluence-userlink user-mention" href="/display/~ana">Ana</a> <time datetime="2026-01-02">02 Jan 2026</time></p>
        <div class="confluence-information-macro confluence-information-macro-note"><p class="title">Heads up</p><span class="aui-icon aui-icon-small aui-iconfont-warning"></span><div class="confluence-information-macro-body"><p>Careful.</p></div></div>
        <div class="code panel pdl"><div class="codeHeader panelHeader pdl"><b>Example</b></div><div class="codeContent panelContent pdl"><pre class="syntaxhighlighter-pre" data-syntaxhighlighter-params="brush: java; gutter: false" data-theme="Confluence">int a = 1 &lt; 2;
</pre></div></div>
        <div class="expand-container"><div class="expand-control"><span class="expand-control-icon"></span><span class="expand-control-text">More</span></div><div class="expand-content"><p>Hidden</p></div></div>
        <p><span class="status-macro aui-lozenge aui-lozenge-success">DONE</span></p>
        <ul class="inline-task-list"><li class="checked">Buy milk</li><li>Call Bob</li></ul>
        <div class="table-wrap"><table class="confluenceTable"><tbody><tr><th class="confluenceTh">A</th></tr><tr><td class="confluenceTd">1</td></tr></tbody></table></div>
        <p><span class="confluence-embedded-file-wrapper"><img class="confluence-embedded-image" src="download/thumbnails/200/300.png?version=1" data-image-src="attachments/200/300.png" data-linked-resource-id="300" width="400"></span></p>
        <div class="contentLayout2"><div class="columnLayout two-equal" data-layout="two-equal"><div class="cell normal" data-type="normal"><div class="innerCell"><p>Left</p></div></div><div class="cell normal"><div class="innerCell"><p>Right</p></div></div></div></div>
        <div class="toc-macro"><ul><li>x</li></ul></div>
        <p>&nbsp;</p>
      `),
    );
    expect(html).not.toContain('page-metadata');
    expect(html).not.toContain('Attachments:');
    expect(html).not.toContain('toc-macro');
    expect(html).not.toContain('<p>&nbsp;</p>');
    expect(html).toContain('<a href="Other_5.html">Other</a>');
    expect(html).toContain('Ana');
    expect(html).toContain('2026-01-02');
    expect(html).toContain('<div data-type="callout" data-callout-type="warning"><p><strong>Heads up</strong></p><p>Careful.</p></div>');
    expect(html).toContain('<p><strong>Example</strong></p><pre><code class="language-java">int a = 1 &lt; 2;</code></pre>');
    expect(html).toContain('<details><summary>More</summary><div data-type="detailsContent"><p>Hidden</p></div></details>');
    expect(html).toContain('<span data-type="status" data-color="green">DONE</span>');
    expect(html).toContain('<ul data-type="taskList"><li data-type="taskItem" data-checked="true">');
    expect(html).toContain('<li data-type="taskItem" data-checked="false"><label><input type="checkbox"><span></span></label><div><p>Call Bob</p></div></li>');
    expect(html).toContain('<table><tbody><tr><th>A</th></tr><tr><td>1</td></tr></tbody></table>');
    expect(html).toContain('<img src="attachments/200/300.png" width="400">');
    expect(html).not.toContain('data-image-src');
    expect(html).toContain('<div data-type="columns" data-layout="two_equal"><div data-type="column"><p>Left</p></div><div data-type="column"><p>Right</p></div></div>');
  });

  it('falls back to the whole body without main-content', () => {
    expect(confluenceBodyHtml('<html><body><p>Bare</p></body></html>')).toBe('<p>Bare</p>');
  });
});
